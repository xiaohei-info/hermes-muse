def check(name, ok, detail=""):
    print(f"{name} {'PASS' if ok else 'FAIL'} {json.dumps(detail, ensure_ascii=False, sort_keys=True, default=str)[:600]}")
    if not ok:
        FAILED.append(name)


class Ctx:
    """The PluginContext calls register() makes."""

    def __init__(self):
        self.calls = []
        for name in ("register_tool", "register_skill", "register_system_prompt_section", "register_hook", "on_unload"):
            setattr(self, name, lambda *a, _n=name, **k: self.calls.append((_n, a, k)))


def user_turn(home, session, text, at):
    with sqlite3.connect(home / "state.db") as db:
        db.execute("INSERT OR IGNORE INTO sessions (id, source, chat_type, title, started_at) VALUES (?,?,?,?,?)",
                   (session, "cli", "dm", "Chat", at - 60))
        db.execute("INSERT INTO messages (session_id, role, content, timestamp, message_uid) VALUES (?,?,?,?,?)",
                   (session, "user", text, at, f"uid-{at}"))


def v1_jobs(home):
    """0.3.x installation: launchers and jobs with installation markers; the user paused the weekly review."""
    from cron.jobs import create_job, pause_job
    ids = {}
    for key, schedule in V1_KEYS.items():
        (home / "scripts").mkdir(exist_ok=True)
        (home / "scripts" / f"hermes-muse-{key}.py").write_text(V1_HEADER + "print('{\"wakeAgent\": false}')\n")
        job = create_job(prompt=f"[hermes-muse:abc123:{key}]\n0.3 prompt for {key}", schedule=schedule, name=f"muse-{key}",
                         deliver="bot-chat" if key == "proactive-watch" else "local", script=f"hermes-muse-{key}.py")
        ids[key] = job["id"]
    pause_job(ids["weekly-governance-review"], reason="user paused")
    ids["keep-me"] = create_job(prompt="Unrelated user job", schedule="0 12 * * *", name="keep-me", deliver="local")["id"]
    return ids


def prompt(key):
    from hermes_muse.install import JOBS
    return (ROOT / "prompts" / "jobs" / f"{JOBS[key][0]}.md").read_text()


def part_install(home, ids):
    from hermes_muse.host import HostAdapter
    from hermes_muse.install import MARKER, PROMPTS_BACKUP, install, route
    adapter = HostAdapter(home)
    first = install(adapter, ROOT)
    jobs = {j["id"]: j for j in __import__("cron.jobs", fromlist=["x"]).list_jobs(include_disabled=True)}
    refreshed = {k: jobs[i] for k, i in ids.items() if k in V1_KEYS}
    health_job = next((j for j in jobs.values() if j.get("script") == "hermes-muse-health.py"), None)
    check("install: v1 state migrated, marker removed, templates created",
          first["migration"] and first["migration"].get("reason") != "already_migrated" and not (home / MARKER).exists()
          and (home / "muse" / "state-v2.db").is_file() and "AGENTS.md" in first["templates"],
          {"migration": {k: first["migration"].get(k) for k in ("shape", "counts")}, "templates": first["templates"]})
    check("install: 0.3.x jobs refreshed in place (same ids, new prompts, user schedule/pause kept), monthly paused",
          all(first["jobs"][k] == ids[k] for k in V1_KEYS if k != "monthly-system-audit")
          and all(prompt(k) == refreshed[k]["prompt"] for k in V1_KEYS if k != "monthly-system-audit")
          and refreshed["memory-upkeep"]["schedule"].get("expr") == "15 * * * *"
          and refreshed["weekly-governance-review"]["state"] == "paused"
          and refreshed["monthly-system-audit"]["state"] == "paused" and "weekly digest" in refreshed["monthly-system-audit"]["paused_reason"]
          and jobs[ids["keep-me"]]["prompt"] == "Unrelated user job",
          {k: (j["state"], j["schedule"].get("expr")) for k, j in refreshed.items()})
    check("install: Health no_agent cron created; 0.3.x prompts (with markers) backed up",
          health_job and health_job.get("no_agent") and first["health_cron"] == health_job["id"]
          and sorted(json.loads((home / PROMPTS_BACKUP).read_text())) == sorted(ids[k] for k in V1_KEYS),
          {"health": health_job and health_job["name"], "jobs": len(jobs)})
    deliver_job = jobs.get(first["jobs"]["deliver"]) or {}
    check("install: muse-deliver no-agent job (no prompt) every 10 minutes on the user's route",
          deliver_job.get("no_agent") and not deliver_job.get("prompt") and deliver_job.get("deliver") == route(adapter)
          and deliver_job["schedule"].get("expr") == "*/10 * * * *", {f: deliver_job.get(f) for f in ("name", "deliver", "schedule")})

    # 0.4.1 one-shot delivery jobs: a finished one is removed by the upgrade, one whose notice is still sending stays.
    from cron.jobs import create_job, update_job
    from hermes_muse.kernel import Kernel, notifier
    k = Kernel(home, adapter=adapter)
    notifier.draft(k, text="Legacy delivery", priority="urgent", upstream_id="wp6-legacy", title="Legacy", now=time.time())
    waiting = notifier.claim(k, deliver_job, "e-legacy", time.time())[0]["payload"]["delivery_key"]
    legacy = {}
    for key in ("old1", waiting):
        adapter.cron.write_script(f"hermes-muse-deliver-{key}.py", "print('old')\n")
        legacy[key] = create_job(prompt=None, schedule="2099-01-01T00:00:00+00:00", name=f"muse-deliver-{key}",
                                 deliver="bot-chat", script=f"hermes-muse-deliver-{key}.py", no_agent=True)["id"]
        update_job(legacy[key], {"enabled": False, "state": "completed"})
    again = install(adapter, ROOT)
    after = {j["id"]: j for j in __import__("cron.jobs", fromlist=["x"]).list_jobs(include_disabled=True)}
    check("install: idempotent (already migrated, same jobs, backup kept)",
          again["migration"].get("reason") == "already_migrated" and again["jobs"] == first["jobs"]
          and set(after) == set(jobs) | {legacy[waiting]} and again["prompts_backed_up"] is False, {"jobs": len(after)})
    check("install: settled 0.4.1 one-shot deliveries removed with their launcher; one awaiting its receipt kept; user jobs untouched",
          again["one_shots_removed"] == 1 and legacy["old1"] not in after and legacy[waiting] in after and ids["keep-me"] in after
          and not (home / "scripts" / "hermes-muse-deliver-old1.py").exists(), {"removed": again["one_shots_removed"]})
    return adapter


def part_entry(home, ids):
    from cron.executions import create_execution, mark_execution_running
