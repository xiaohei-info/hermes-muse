    from cron.scheduler_script import _run_job_script
    from hermes_muse import entry
    from hermes_muse.install import MARKER
    from hermes_muse.kernel.store import Store

    now = time.time()
    user_turn(home, "chat", "Book the dentist for next week", now)  # after the migration watermark
    execution = create_execution(ids["memory-upkeep"], source="test")
    mark_execution_running(execution["id"])
    ok, out = _run_job_script("hermes-muse-memory-upkeep.py")  # the real launcher, as the scheduler runs it
    line = json.loads(out.strip().splitlines()[-1]) if ok and out.strip() else {}
    packet = line.get("packet") or {}
    runs = Store.for_home(home, readonly=True).query("run", natural_key=execution["id"])
    check("pre-run: launcher -> cron_entry -> intake packet with the new user turn; run registered via start_run",
          ok and _parse_wake_gate(out) and packet.get("type") == "intake" and packet.get("schema")
          and any("dentist" in i.get("excerpt", "") for i in packet.get("items", []))
          and runs and runs[0]["payload"]["packet_id"] == packet["id"],
          {"ok": ok, "items": len(packet.get("items", [])), "run": runs and runs[0]["state"], "out": out[:200] if not ok else ""})
